/**
 * 単位を型で分ける（ブランド型）— 実行時は同じ数でも、意味の違う値を別の型にする。
 *
 * 区間ごとに 0 へ戻る番号と、始めから通して数える番号は、どちらもただの数で、最初の区間の
 * 間は値まで同じになる。片方を受け取る所へもう片方を渡しても型検査は止めず、最初の区間だけを
 * 使うテストも通る。違いが出るのは2つ目の区間からになる。
 *
 * ここでは数に型の上だけの印を付け、印ごとに別の型として扱わせる。
 *
 * ```ts
 * type SectionIndex = Brand<number, 'SectionIndex'>; // 区間ごとに 0 へ戻る番号
 * type OverallIndex = Brand<number, 'OverallIndex'>; // 始めから通して数える番号
 * ```
 *
 * 守られるのは片方向だけ。
 *
 * - 印の付いた値は、ただの数を受け取る所へそのまま渡せる。計算や表示のたびに印を外さなくてよい
 * - ただの数や別の印の値を、印の付いた値を受け取る所へ渡すと、型エラーになる
 * - 印の付いた値どうしを足すと、ただの数に戻る。次の番号も、もう一度印を付けて作る
 * - 印を付ける書き方（`value as OverallIndex`）は、ただの数ならどれにも使え、型検査を通る。
 *   別の印の値にそのまま付けると型エラーになるが、ただの数を経れば通る。区間の中で数えた値に
 *   通しの番号の印を付けても止まらないので、印を付ける場所を少なくする
 *
 * 印は文字列で見分ける。同じ文字列の印を別の名前で2度定義すると、同じ型になって区別できない。
 * 型ごとに違う文字列を付ける。
 */

/**
 * 印を置く項目の名前。値は無く、型の上にだけある。外に出さないので、印の項目を持つ値を
 * 手で組み立てることはできない。印を付けるのは `as` か、型の述語を返す関数
 * （`value is OverallIndex`・`asserts value is OverallIndex`）で、どちらも型検査は値の中身を見ない。
 */
declare const brand: unique symbol;

/**
 * `T` に印 `B` を付けた型。
 *
 * 実行時には何も残らない。印の付いた値は `T` の値そのもので、変換の手間はかからない。
 */
export type Brand<T, B extends string> = T & { readonly [brand]: B };
